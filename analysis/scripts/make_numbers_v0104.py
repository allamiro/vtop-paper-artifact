#!/usr/bin/env python3
"""Write research/analysis/v0104/NUMBERS.md: every manuscript number of the change ledger with its v0.10.2 and its
v0.10.4 value side by side, and a computed flag where the claim's direction may have changed.

  research/.venv/bin/python research/analysis/scripts/analyze.py --set v0104
  research/.venv/bin/python research/analysis/scripts/make_numbers_v0104_core.py   # v0.7.0 vs v0.10.4 (NUMBERS-v070.md)
  research/.venv/bin/python research/analysis/scripts/make_numbers_v0104.py

make_numbers_v0104_core.py is make_numbers_v0102.py with the v0.10.4 inputs (same rows, same value code). Its claim and
direction texts were written for v0.10.2 and are NOT re-judged there; this script re-judges direction from the values:
every "x [lo, hi]" interval is classed as above 0, below 0 or including 0, and a row whose classes differ between the
builds is flagged DIRECTION CHANGED. Other rows are "same value" or "value changed". Read the flagged rows by hand.
"""
from __future__ import annotations

import re
from pathlib import Path

RES = Path(__file__).resolve().parents[2]
OLD, NEW, OUT = RES / "analysis/v0102/NUMBERS.md", RES / "analysis/v0104/NUMBERS-v070.md", RES / "analysis/v0104/NUMBERS.md"
CI = re.compile(r"(-?\d+(?:\.\d+)?)%?\s*\[(-?\d+(?:\.\d+)?)%?,\s*(-?\d+(?:\.\d+)?)%?\]")


def table(p: Path) -> list[list[str]]:
    rows, on = [], False
    for line in p.read_text().splitlines():
        if line.startswith("| # |"):
            on = True
            continue
        if on and line.startswith("|---"):
            continue
        if on and line.startswith("| "):
            rows.append([c.strip() for c in re.split(r"(?<!\\)\|", line)[1:-1]])
        elif on and rows:
            break
    return rows


def classes(cell: str) -> list[str]:
    out = []
    for _, lo, hi in CI.findall(cell):
        lo, hi = float(lo), float(hi)
        out.append("above 0" if lo > 0 else "below 0" if hi < 0 else "includes 0")
    return out


old, new = table(OLD), table(NEW)
assert [r[0] for r in old] == [r[0] for r in new], "row ids differ between the two NUMBERS tables"
lines, flagged, changed = [], [], 0
for o, n in zip(old, new):
    v2, v4 = o[4], n[4]
    c2, c4 = classes(v2), classes(v4)
    if c2 != c4:
        flag = "**DIRECTION CHANGED**: " + "; ".join(f"{a} → {b}" for a, b in zip(c2, c4) if a != b) \
            + (" (interval count differs)" if len(c2) != len(c4) else "")
        flagged.append((n[0], n[1], n[2], v2, v4, flag))
    elif v2 == v4:
        flag = "same value"
    else:
        flag = "value changed"
        changed += 1
    lines.append(f"| {n[0]} | {n[1]} | {n[2]} | {v2} | {v4} | {n[5]} | {flag} |")

hdr = f"""# Manuscript numbers: vtop-engine v0.10.2 vs v0.10.4 (decision D16)

Generated by `research/analysis/scripts/make_numbers_v0104.py` from `research/analysis/v0102/NUMBERS.md` (v0.10.2,
engine 0abf116) and `research/analysis/v0104/NUMBERS-v070.md` (the same rows computed on v0.10.4, engine be5b419, by
`make_numbers_v0104_core.py` from `research/analysis/v0104/summary.json`). Checked by `verify_v0104_data.py`, which
recomputes every v0.10.4 value from the run files. Do not edit by hand: re-run the scripts.

**Flag** is computed, not judged: an interval whose class (above 0 / includes 0 / below 0) differs between the builds
is a **DIRECTION CHANGED** row; the claim must be re-read. "value changed" keeps its direction. The claim texts are
those of the v0.10.2 ledger.

Read first (v0.10.4 campaign, 2026-11-22):
- **Local timing (RQ3, local store) is not comparable between the builds.** v0.10.4 run-mode throughput is about 40%
  lower in every cell, size-only included. The cause is the localfs backend's durable writes since v0.10.3 (#827: fsync
  of file and directory). Per batch, object upload rose from 0.0 to 12.6-20.3 ms and manifest upload from 0.0 to
  8.5-10.5 ms; compress, checksum and verify are unchanged. An interleaved A/B on one host gave v0.10.4 / v0.10.2
  throughput 0.61-0.81. Details: `research/analysis/v0104/RQ3-AB.md`.
- **Tamper:** MAC-SWAP-OFF/ON are now caught by verify-manifest (#882, v0.10.3); suspended versioning under a running
  engine wrote 1 object, not 10 (#883, v0.10.4). `state-machine/v0104-repin-notes.md`.
- **PERF:** one Vector run failed on the oracle's tie-break, not on Vector, and was re-judged offline
  (`rq5-cloud/perf/LESSONS.md`).
- **Model rows C3 (no hand-back, no read-order):** the v0.10.2 column keeps the ledger text written before the v010
  single-rule ablation (`state-machine/results/20261121-v010-rule-ablation.*`); the v0.10.4 column reads that run through
  `summary.json` → `rq1_model_ablation`. The ablation is a model result and is the same for both builds.
- **Store SHA-256 on S3 (E5) and WAN read-back:** v0.10.2 was resolved on HDFS only and its read-back grew with the
  round trip; on v0.10.4 store SHA-256 is resolved on BGL and HDFS and the read-back cost is not monotonic in RTT
  (São Paulo, 111 ms, above Tokyo, 147 ms; `rq5_wan.claims.readback_slowdown_increases_with_rtt` = false).

{len(flagged)} rows flagged DIRECTION CHANGED; {changed} other rows changed value; {len(lines) - len(flagged) - changed}
unchanged.

## Rows flagged DIRECTION CHANGED

""" + ("\n".join(f"- **{r[0]}** ({r[1]}): {r[2]}: v0.10.2 {r[3]}; v0.10.4 {r[4]}. {r[5]}" for r in flagged) or "none") + """

## All numbers

| # | Where | Claim / number (v0.10.2 ledger text) | v0.10.2 | v0.10.4 [95% CI] | Source (v0.10.4) | Flag |
|---|---|---|---|---|---|---|
"""
OUT.write_text(hdr + "\n".join(lines) + "\n")
print("wrote", OUT, len(lines), "rows;", len(flagged), "direction changed;", changed, "value changed")
