#!/usr/bin/env python3
"""RQ5 cloud smoke test driver: vtop-engine v0.10.1 against real Amazon S3 (runs on the VM).

For each mode: write a config, `vtopctl validate --print-effective`, run `vtopctl run` until
the ledger shows the input committed to its last byte (or a timeout), stop the engine with
SIGTERM, then run the independent oracle (oracle.py) and VTOP's own read-only checks
(`scrub`, `audit-coverage --check-storage`). One JSON file per mode, plus run.json.

The config text follows research/experiments/lib/vtoplab.py Run._write_config and the
upload block of MinioRun in rq3-cost-ablation/code/exp_minio_cost.py; the variant values
are those of exp_cost.py VARIANTS. Differences for real S3 and v0.10.1 are commented.
Every key is documented in docs/configure/reference.md at v0.10.1 (see README.md).
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import shutil
import signal
import sqlite3
import subprocess
import time
import urllib.request
from pathlib import Path

import oracle

MiB = 2**20
# name -> (checksum.algorithm, compression.type, upload.require_strong_verification)
MODES = {
    "size-only": ("none", "zstd", False),         # exp_cost.py "size-only"
    "sha256-store": ("sha256", "zstd", True),     # exp_cost.py "sha256"; objects stay < 8 MiB
    "blake3-readback": ("blake3", "zstd", True),  # exp_cost.py "blake3"
    "sha256-multipart": ("sha256", "none", True), # exp_cost.py "sha256-nocomp"; 16 MiB objects
}
# object_check messages the engine logs with verification_passed (engine.rs:1545-1560); the
# strings are VerificationResult messages in s3_native.rs:1373, 1415-1416, 1435 and base.rs:391.
SVC, RB = "S3 service-computed SHA-256 verified", ("stored content SHA-256 verified by read-back (no "
                                                    "service whole-object checksum; multipart or unchecked upload)")
LOG_EXPECT = {  # mode -> (allowed messages, messages that must appear)
    "size-only": ({"object present and size matches (checksums disabled)"},) * 2,
    "sha256-store": ({SVC},) * 2,
    "blake3-readback": ({"stored content BLAKE3 verified"},) * 2,
    "sha256-multipart": ({SVC, RB}, {RB}),
}
# upload.multipart_threshold_bytes per mode. Default 8 MiB (config.rs:1401, reference.md:238).
# A 16 MiB max_bytes batch of SSH lines is ~32 MiB uncompressed in `vtopctl run` (observed: 33,554,257 B,
# README "Batch size"), so 64 MiB keeps every object single-PUT; sha256-multipart keeps the
# default 8 MiB on purpose, so its 32 MiB objects go multipart and are read back.
MULTIPART_THRESHOLD = {"size-only": 64 * MiB, "sha256-store": 64 * MiB,
                       "blake3-readback": 64 * MiB, "sha256-multipart": 8 * MiB}
SDK_ENV = ["AWS_REQUEST_CHECKSUM_CALCULATION", "AWS_RESPONSE_CHECKSUM_VALIDATION",
           "AWS_ENDPOINT_URL", "AWS_ENDPOINT_URL_S3", "VTOP_S3_ENDPOINT_URL",
           "VTOP_S3_FORCE_PATH_STYLE", "VTOP_S3_VERIFY_TLS", "VTOP_S3_TRANSPORT",
           "AWS_REGION", "AWS_DEFAULT_REGION", "AWS_PROFILE", "AWS_ACCESS_KEY_ID"]
# Removed from the engine's environment: endpoint and override variables (real S3, config only).
STRIP_ENV = ["AWS_ENDPOINT_URL", "AWS_ENDPOINT_URL_S3", "VTOP_S3_ENDPOINT_URL",
             "VTOP_S3_FORCE_PATH_STYLE", "VTOP_S3_VERIFY_TLS", "VTOP_S3_TRANSPORT"]


def config_text(mode, root: Path, bucket: str, prefix: str) -> str:
    algo, codec, strong = MODES[mode]
    glob = str(root / "input" / "*.log")
    return f"""# generated by research/experiments/rq5-cloud/smoke/smoke.py ({mode}) for vtop-engine v0.10.1
engine:
  name: smoke
  tenant: smoke
  state_store: "sqlite://{root / 'state' / 'vtop.db'}"
  work_dir: {root / 'work'}
batching:
  max_records: 1000000
  max_bytes: {16 * MiB}
  max_batch_age_seconds: 2
  idle_poll_interval_ms: 200
  max_concurrent_batches: 8
compression:
  type: {codec}
  level: 3
checksum:
  algorithm: {algo}
manifest:
  verification_receipts: true   # v0.10.x key: writes <batch>.receipt.json with the method used
sources:
  kafka: {{enabled: false, bootstrap_servers: ["localhost:9092"], consumer_group: lab}}
  file: {{enabled: true, paths: ["{glob}"]}}
  syslog_spool: {{enabled: false, paths: ["{glob}"]}}
upload:
  backend: s3_native
  # real S3: no endpoint_url, force_path_style or verify_tls (defaults: SDK endpoint, virtual-host, TLS on)
  region: us-east-1
  bucket: {bucket}
  prefix: "{prefix}"
  create_bucket: false
  require_strong_verification: {str(strong).lower()}
  multipart_threshold_bytes: {MULTIPART_THRESHOLD[mode]}
  multipart_part_size_bytes: {8 * MiB}
""" + lab_block()


def lab_block() -> str:
    """Local dry run only (SMOKE_LAB_ENDPOINT=http://127.0.0.1:PORT, MinIO). Never set on EC2."""
    ep = os.environ.get("SMOKE_LAB_ENDPOINT")
    return f"  endpoint_url: {ep}\n  force_path_style: true\n  verify_tls: false\n" if ep else ""


def sh(*args, env=None, timeout=900) -> dict:
    try:
        p = subprocess.run([str(a) for a in args], capture_output=True, text=True, env=env, timeout=timeout)
    except (FileNotFoundError, subprocess.TimeoutExpired) as e:
        return {"cmd": [str(a) for a in args], "rc": None, "stdout": "", "stderr": repr(e)}
    return {"cmd": [str(a) for a in args], "rc": p.returncode, "stdout": p.stdout[-20000:], "stderr": p.stderr[-5000:]}


def committed_end(db: Path, path: str) -> int:
    if not db.exists():
        return 0
    try:
        con = sqlite3.connect(f"file:{db}?mode=ro", uri=True, timeout=30)
        rows = con.execute("SELECT progress_end_json FROM batches WHERE state='source_committed'").fetchall()
        con.close()
    except sqlite3.OperationalError:
        return 0
    ends = [int(json.loads(r[0])["end_byte"]) for r in rows if json.loads(r[0]).get("path") == path]
    return max(ends, default=0)


def ledger_states(db: Path) -> dict:
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True, timeout=30)
    try:
        return dict(con.execute("SELECT state, COUNT(*) FROM batches GROUP BY state").fetchall())
    finally:
        con.close()


def log_summary(log: Path) -> dict:
    """Engine JSON log lines: verification messages, warnings, errors, key decisions."""
    out = {"verification_passed": [], "shutdown": None, "warn": 0, "error": 0, "warn_or_error_samples": [],
           "events": {}, "batch_metrics": [], "unparsed_lines": 0}
    for line in log.read_text(errors="replace").splitlines():
        try:
            rec = json.loads(line)
        except ValueError:
            out["unparsed_lines"] += 1
            continue
        f, level = rec.get("fields", {}), rec.get("level", "")
        msg = f.get("message", "")
        if msg.startswith("verification_passed"):
            out["verification_passed"].append({k: f.get(k) for k in (
                "batch_id", "verification_class", "object_check", "manifest_check")})
        if msg.startswith("shutdown flush"):
            out["shutdown"] = msg
        if msg == "batch_metrics":
            out["batch_metrics"].append(f)
        if "event" in f:
            out["events"][f["event"]] = out["events"].get(f["event"], 0) + 1
        if level in ("WARN", "ERROR"):
            out["warn" if level == "WARN" else "error"] += 1
            if len(out["warn_or_error_samples"]) < 20:
                out["warn_or_error_samples"].append({"level": level, "message": msg[:600]})
    return out


def run_mode(mode, a, env) -> dict:
    root = Path(a.work) / mode
    shutil.rmtree(root, ignore_errors=True)
    for d in ("input", "state", "work", "logs"):
        (root / d).mkdir(parents=True)
    src = root / "input" / "ssh.log"
    shutil.copyfile(a.input, src)
    prefix = f"smoke/data/{a.run_id}/{mode}/"
    cfg = root / "config.yaml"
    cfg.write_text(config_text(mode, root, a.bucket, prefix))
    rec = {"mode": mode, "prefix": prefix, "config": cfg.read_text(), "input_bytes": src.stat().st_size,
           "validate": sh(a.vtopctl, "--json", "validate", "--config", cfg, "--print-effective", env=env)}
    db = root / "state" / "vtop.db"
    log = root / "logs" / "engine.jsonl"
    t0 = time.perf_counter()
    with open(log, "wb") as fh:
        p = subprocess.Popen([a.vtopctl, "run", "--config", str(cfg)], stdout=fh, stderr=subprocess.STDOUT, env=env)
        series, last = [], 0
        while True:
            c = committed_end(db, str(src))
            if c != last:
                series.append([round(time.perf_counter() - t0, 3), c])
                last = c
            if c >= src.stat().st_size or p.poll() is not None or time.perf_counter() - t0 > a.timeout:
                break
            time.sleep(0.05)
        wall = time.perf_counter() - t0
        exited_early = p.poll() is not None
        if not exited_early:
            p.send_signal(signal.SIGTERM)
        try:
            _, status, ru = os.wait4(p.pid, 0)
            cpu, rss = ru.ru_utime + ru.ru_stime, ru.ru_maxrss * 1024  # Linux ru_maxrss is KiB
        except ChildProcessError:
            status, cpu, rss = p.returncode, None, None
    drained = committed_end(db, str(src)) >= src.stat().st_size
    rec.update({"drained": drained, "engine_exited_before_drain": exited_early and not drained,
                "wall_s": round(wall, 3), "cpu_s": cpu, "max_rss_bytes": rss, "exit_status": status,
                "commit_series": series, "ledger_states": ledger_states(db) if db.exists() else {},
                "engine_log": log_summary(log)})
    rec["oracle"] = oracle.check(str(db), str(src), a.bucket, prefix, mode)
    # VTOP's own read-only re-checks (not part of the pass rule; recorded for comparison).
    rec["vtop_scrub"] = sh(a.vtopctl, "--json", "scrub", "--config", cfg, env=env)
    rec["vtop_audit_coverage"] = sh(a.vtopctl, "--json", "audit-coverage", "--config", cfg, "--check-storage", env=env)
    vp = rec["engine_log"]["verification_passed"]
    # Pass = drained + committed + oracle pass. A ledger with failed or replayed rows still
    # passes if the oracle does, but is flagged: a smoke run on a healthy store should be clean.
    rec["clean_ledger"] = rec["ledger_states"].keys() <= {"source_committed"}
    seen = {v["object_check"] for v in vp}
    allowed, required = LOG_EXPECT[mode]
    rec["log_object_checks"] = sorted(seen)
    rec["log_as_expected"] = bool(seen) and seen <= allowed and required <= seen
    rec["pass"] = bool(drained and rec["log_as_expected"] and rec["oracle"]["pass"])
    shutil.copy(log, Path(a.out) / f"engine-{mode}.jsonl")
    return rec


def imds(path: str) -> str | None:
    try:
        tok = urllib.request.urlopen(urllib.request.Request(
            "http://169.254.169.254/latest/api/token", method="PUT",
            headers={"X-aws-ec2-metadata-token-ttl-seconds": "300"}), timeout=2).read().decode()
        return urllib.request.urlopen(urllib.request.Request(
            f"http://169.254.169.254/latest/{path}", headers={"X-aws-ec2-metadata-token": tok}), timeout=2).read().decode()
    except Exception:  # noqa: BLE001
        return None


