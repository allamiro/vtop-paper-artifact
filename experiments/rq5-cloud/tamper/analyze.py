#!/usr/bin/env python3
"""Summarize E-RQ5-TAMPER result directories (run locally).

  python3 analyze.py results/<run_a> [results/<run_b> ...] [--out DIR]

Each directory holds run.json and cases.jsonl written by tamper.py. For every case and verifier the expected verdict
(from the hypotheses and the engine maintainer's evidence) is compared with the observed one. Each check is labelled:

  caught       the defence reported, refused or replayed the tamper, as expected
  prevented    the store or the database refused the tamper request itself, as expected
  NOT CAUGHT   the expected verdict is the wrong one by design (a stated limit) and that wrong verdict was observed:
               the limit is measured
  as expected  a control or a correct non-finding (e.g. recovery commits because the pinned evidence is intact)
  DIFFERS      the observed verdict is not the expected one (a finding about the hypothesis, the engine, or the store)

With two or more directories (e.g. local MinIO and AWS), a last column says whether they agree per case.
Writes ANALYSIS.md and summary.json to --out (default: the first directory). Exit status 1 if any case raised an
error or a re-implementation check failed; DIFFERS alone does not fail the script (it is a result).
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

CAUGHT = {  # verifier prefix -> verdicts that mean "the defence reported it"
    "scrub": lambda v: v not in ("ok", "limited", "locked", None, True),
    "vm": lambda v: v == "failed",
    "recovery": lambda v: v == "replayed",
    "check_storage": lambda v: v == "failed",
    "engine_start": lambda v: v == "refused",
    "audit_verify": lambda v: v == "failed",
    "anchor": lambda v: v == "differs",
    "coverage": lambda v: v == "hole",
}
PREVENTED = {"store": "refused", "sql": "refused", "running_engine": "committed_nothing"}


def label(check: dict) -> str:
    v, verifier = check["observed"], check["verifier"]
    if not check["match"]:
        return "DIFFERS"
    if check["limit"]:
        return "NOT CAUGHT"
    base = verifier.split(".")[0]
    if base in PREVENTED:
        return "prevented" if v == PREVENTED[base] else "as expected"
    for prefix, fn in CAUGHT.items():
        if base.startswith(prefix):
            return "caught" if fn(v) else "as expected"
    return "as expected"


def case_outcome(rec: dict) -> str:
    if rec.get("skipped"):
        return "skipped"
    if rec.get("error"):
        return "ERROR"
    labels = [c["label"] for c in rec["checks"]]
    if "DIFFERS" in labels:
        return "DIFFERS"
    out = []
    if "caught" in labels or "prevented" in labels:
        out.append("caught" if "caught" in labels else "prevented")
    if "NOT CAUGHT" in labels:
        out.append("NOT CAUGHT (limit)")
    return " + ".join(out) or "as expected"


def load(d: Path) -> tuple[dict, list[dict]]:
    meta = json.loads((d / "run.json").read_text())
    recs = {}
    for line in (d / "cases.jsonl").read_text().splitlines():
        r = json.loads(line)
        recs[r["id"]] = r          # a re-run of a case id replaces the earlier line
    for r in recs.values():
        for c in r.get("checks", []):
            c["label"] = label(c)
        r["outcome"] = case_outcome(r)
    return meta, list(recs.values())


def fmt(v) -> str:
    return "–" if v is None else str(v).lower() if isinstance(v, bool) else str(v)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dirs", nargs="+")
    ap.add_argument("--out")
    a = ap.parse_args()
    runs = []
    for d in map(Path, a.dirs):
        meta, recs = load(d)
        where = "local MinIO" if meta.get("endpoint", "aws") != "aws" else "AWS S3"
        runs.append({"dir": d.name, "where": where, "meta": meta, "recs": recs})
    out = Path(a.out or a.dirs[0])
    out.mkdir(parents=True, exist_ok=True)
    bad = False
    md = ["# E-RQ5-TAMPER analysis", "", "Generated by `analyze.py`; do not edit by hand.", ""]
    for r in runs:
        m = r["meta"]
        rc = m.get("reimpl_check", {})
        bad |= not rc.get("ok", False)
        cnt = Counter(x["outcome"] for x in r["recs"])
        chk = Counter(c["label"] for x in r["recs"] for c in x.get("checks", []))
        md += [f"## {r['where']}: `{r['dir']}`", "",
               f"- engine: {m.get('vtopctl_version')} (`vtopctl` SHA-256 {m.get('vtopctl_sha256', '')[:16]}…), "
               f"commit {m.get('vtop_commit', '–')}, archive {str(m.get('tarball_sha256', '–'))[:16]}…",
               f"- input: {m['input']['bytes']} B, SHA-256 {m['input']['sha256'][:16]}…; batches of "
               f"{m.get('batching_max_bytes')} B",
               f"- buckets: {m.get('preflight')}",
               f"- re-implementation check (manifest/receipt hash+MAC, audit links vs the engine's own): "
               f"{'OK' if rc.get('ok') else 'FAILED'}",
               f"- cases: {len(r['recs'])}; outcomes: {dict(cnt)}; checks: {dict(chk)}", ""]
        errs = [x for x in r["recs"] if x.get("error")]
        bad |= bool(errs)
        for x in errs:
            md.append(f"- **ERROR** {x['id']}: {x['error']}")
    base = runs[0]
    others = {r["dir"]: {x["id"]: x for x in r["recs"]} for r in runs[1:]}
    md += ["## Cases", "",
           "Verdicts: `observed` (with `expected` when they differ). Limit checks (NOT CAUGHT by design) are marked *L*.",
           ""]
    head = "| Case | H | Attacker | Tamper | Verifier verdicts | Outcome |" + "".join(
        f" `{r['dir']}` agrees? |" for r in runs[1:])
    md += [head, "|" + "---|" * (6 + len(runs) - 1)]
    for x in base["recs"]:
        cells = []
        for c in x.get("checks", []):
            s = f"{c['verifier']}={fmt(c['observed'])}"
            if not c["match"]:
                s += f" (**expected {fmt(c['expected'])}**)"
            if c["limit"]:
                s += " *L*"
            cells.append(s)
        if x.get("skipped"):
            cells = [x["skipped"]]
        row = (f"| {x['id']} | {x.get('hypothesis', '')} | {x.get('attacker') or ''} | {x.get('action', '')} | "
               f"{'; '.join(cells)} | {x['outcome']} |")
        for name, recs in others.items():
            y = recs.get(x["id"])
            if not y:
                row += " not run |"
            elif y.get("skipped") or x.get("skipped"):
                row += " – |"
            else:
                same = [c["observed"] for c in x["checks"]] == [c["observed"] for c in y["checks"]]
                row += " yes |" if same else f" **no**: {y['outcome']} |"
        md.append(row)
    notes = [x for x in base["recs"] if x.get("note")]
    if notes:
        md += ["", "## Case notes", ""] + [f"- **{x['id']}**: {x['note']}" for x in notes]
    md += ["", "## Facts recorded per case (selected)", ""]
    for x in base["recs"]:
        f = {k: v for k, v in (x.get("facts") or {}).items()
             if k in ("original_object_still_stored", "original_manifest_still_stored", "locked_version_intact",
                      "receipt_rewritten", "manifest_versions", "versioning_after", "deleted_row_of")}
        extra = {}
        for k, v in x.get("verdicts", {}).items():
            if isinstance(v, dict) and v.get("forged_content_committed"):
                extra[k + ".forged_content_committed"] = True
            if k == "running_engine":
                extra["batch_failed_errors"] = v.get("batch_failed_errors")
            if k == "store":
                extra["store_errors"] = sorted({c.get("error", "")[:90] for c in v.get("calls", []) if c.get("error")})
            if k == "engine_start":
                extra["message"] = (v.get("messages") or [""])[-1][:160]
        if f or extra:
            md.append(f"- {x['id']}: {json.dumps({**f, **extra})}")
    (out / "ANALYSIS.md").write_text("\n".join(md) + "\n")
    summary = {r["dir"]: {"where": r["where"],
                          "outcomes": dict(Counter(x["outcome"] for x in r["recs"])),
                          "cases": {x["id"]: {"outcome": x["outcome"],
                                              "checks": [{k: c[k] for k in ("verifier", "expected", "observed", "label")}
                                                         for c in x.get("checks", [])]} for x in r["recs"]}}
               for r in runs}
    (out / "summary.json").write_text(json.dumps(summary, indent=1, default=str))
    print("\n".join(md[: 12 + 8 * len(runs)]))
    print(f"\nwrote {out / 'ANALYSIS.md'} and {out / 'summary.json'}")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
