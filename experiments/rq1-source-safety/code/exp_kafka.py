#!/usr/bin/env python3
"""E-RQ1-F (Kafka): crash and fault injection with the Kafka source.

Kafka is the source whose progress is committed *externally* (broker
consumer-group offsets), so it exercises the asymmetric cases of the
protocol. Setup:

  * a single-node Kafka 3.9.1 broker in Docker (KRaft), port 9092;
  * topic ``ssh-p1``: SSH.log, 1 partition (655,147 records);
  * topic ``hdfs-p4``: first 2,000,000 HDFS_v1 lines, 4 partitions;
  * ground truth: the topic is read back once with the console consumer
    (partition, offset -> value), independent of VTOP.

Each trial uses a fresh consumer group, injects K SIGKILLs at random times
and one broker outage (``docker pause`` for a random window, so reads and
offset commits fail), then drains. The oracle checks after every kill and
at the end that the broker's committed offset of every partition never
exceeds the byte-exact verified archive prefix, and counts duplicates.
"""
from __future__ import annotations

import argparse
import json
import random
import shutil
import subprocess
import sys
import threading
import time
from pathlib import Path

import zstandard

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "lib"))
from vtoplab import DATASET_FILES, VTOP_COMMIT, VTOPCTL, Run, Variant, host_info  # noqa: E402

KAFKA_IMAGE = "apache/kafka:3.9.1"
CONTAINER = "vtop-lab-kafka"
KBIN = "/opt/kafka/bin"
TOPICS = {"ssh-p1": ("ssh", None, 1), "hdfs-p4": ("hdfs", 2_000_000, 4)}


def sh(*args, **kw):
    return subprocess.run(list(args), capture_output=True, text=True, **kw)


def kexec(*args, stdin=None):
    cmd = ["docker", "exec", "-i" if stdin else "", CONTAINER, *args]
    cmd = [c for c in cmd if c]
    return subprocess.run(cmd, stdin=stdin, capture_output=True, text=True)


def broker_up():
    sh("docker", "rm", "-f", CONTAINER)
    r = sh("docker", "run", "-d", "--name", CONTAINER, "-p", "9092:9092", KAFKA_IMAGE)
    assert r.returncode == 0, r.stderr
    for _ in range(120):
        if kexec(f"{KBIN}/kafka-topics.sh", "--bootstrap-server", "localhost:9092", "--list").returncode == 0:
            return
        time.sleep(1)
    raise RuntimeError("kafka did not start")


def prepare_topics(work: Path) -> dict:
    """Create and fill topics; return ground truth {topic: {partition: [values]}}."""
    truth = {}
    for topic, (ds, limit, parts) in TOPICS.items():
        kexec(f"{KBIN}/kafka-topics.sh", "--bootstrap-server", "localhost:9092", "--create", "--topic", topic,
              "--partitions", str(parts), "--replication-factor", "1")
        src = work / f"{topic}.txt"
        with open(DATASET_FILES[ds], "rb") as fi, open(src, "wb") as fo:
            for i, line in enumerate(fi):
                if limit and i >= limit:
                    break
                fo.write(line if line.endswith(b"\n") else line + b"\n")
        with open(src, "rb") as fh:
            r = kexec(f"{KBIN}/kafka-console-producer.sh", "--bootstrap-server", "localhost:9092", "--topic", topic,
                      "--producer-property", "linger.ms=20", "--producer-property", "batch.size=262144", stdin=fh)
        assert r.returncode == 0, r.stderr[-500:]
        n = sum(1 for _ in open(src, "rb"))
        dump = kexec(f"{KBIN}/kafka-console-consumer.sh", "--bootstrap-server", "localhost:9092", "--topic", topic,
                     "--from-beginning", "--timeout-ms", "20000", "--property", "print.partition=true",
                     "--property", "print.offset=true", "--max-messages", str(n))
        t: dict[int, dict[int, bytes]] = {}
        for line in dump.stdout.splitlines():
            # "Partition:0\tOffset:12\tvalue"
            p_, o_, v = line.split("\t", 2)
            t.setdefault(int(p_.split(":")[1]), {})[int(o_.split(":")[1])] = v.encode()
        got = sum(len(x) for x in t.values())
        assert got == n, f"{topic}: ground truth has {got} of {n} records"
        truth[topic] = {p: [d[o] for o in sorted(d)] for p, d in t.items()}  # offsets are 0..k-1 per partition
        for p, d in t.items():
            assert sorted(d) == list(range(len(d))), f"{topic}[{p}] offsets not dense"
    return truth


class KafkaRun(Run):
    def __init__(self, root, variant, topic, group):
        self.topic, self.group = topic, group
        super().__init__(root, variant, {})

    def _write_config(self):
        v = self.v
        self.config.write_text(f"""# generated by exp_kafka.py
engine:
  name: lab
  tenant: lab
  state_store: "sqlite://{self.db}"
  work_dir: {self.work}
batching:
  max_records: {v.max_records}
  max_bytes: {v.max_bytes}
  max_batch_age_seconds: {v.max_age_s}
  idle_poll_interval_ms: 200
  max_concurrent_batches: {v.concurrency}
compression:
  type: {v.compression}
  level: {v.level}
checksum:
  algorithm: {v.checksum}
sources:
  kafka:
    enabled: true
    bootstrap_servers: ["localhost:9092"]
    consumer_group: {self.group}
    topic_include_regex: "^{self.topic}$"
    topic_exclude_regex: "^__.*"
    auto_offset_reset: earliest
    enable_auto_commit: false
  file: {{enabled: false, paths: []}}
  syslog_spool: {{enabled: false, paths: []}}
upload:
  backend: localfs
  local_path: {self.objects}
  bucket: archive
  require_strong_verification: true
""")

    def broker_committed(self) -> dict[int, int]:
        r = kexec(f"{KBIN}/kafka-consumer-groups.sh", "--bootstrap-server", "localhost:9092", "--describe", "--group", self.group)
        out = {}
        for line in r.stdout.splitlines():
            f = line.split()
            if len(f) >= 4 and f[1] == self.topic and f[2].isdigit():
                out[int(f[2])] = int(f[3]) if f[3].isdigit() else 0
        return out

    def ledger_committed(self) -> dict[int, int]:
        import sqlite3
        if not self.db.exists():
            return {}
        con = sqlite3.connect(f"file:{self.db}?mode=ro", uri=True, timeout=30)
        try:
            rows = con.execute("SELECT progress_end_json FROM batches WHERE state='source_committed'").fetchall()
        except sqlite3.OperationalError:
            return {}
        finally:
            con.close()
        out = {}
        for (pj,) in rows:
            p = json.loads(pj)
            out[p["partition"]] = max(out.get(p["partition"], 0), int(p["end_offset"]) + 1)
        return out


def oracle_kafka(run: KafkaRun, truth: dict[int, list[bytes]], committed: dict[int, int]) -> dict:
    iv: dict[int, list[tuple[int, int]]] = {}
    bad, understated, n = [], 0, 0
    for mf in run.objects.rglob("*.manifest.json"):
        n += 1
        m = json.loads(mf.read_bytes())
        sp = m["source_progress"]
        part, start, end = int(sp["partition"]), int(sp["start_offset"]), int(sp["end_offset"])
        obj = run.objects / m["object"]["uri"][len("s3://"):]
        if not obj.exists():
            bad.append("object missing"); continue
        plain = zstandard.ZstdDecompressor().decompress(obj.read_bytes(), max_output_size=1 << 31)
        lines = plain.split(b"\n")
        if lines and lines[-1] == b"":
            lines = lines[:-1]
        real_start = end - len(lines) + 1
        if real_start < 0 or lines != truth[part][real_start:end + 1]:
            bad.append("content differs from topic"); continue
        understated += real_start != start
        iv.setdefault(part, []).append((real_start, end + 1))
    rep = {"manifests": n, "bad_objects": bad, "manifest_start_understated": understated, "partitions": {}}
    unsafe = 0
    for p, values in truth.items():
        xs = sorted(iv.get(p, []))
        prefix, reach, dup_obj, covered = 0, -1, 0, 0
        for s, e in xs:
            if s <= prefix:
                prefix = max(prefix, e)
            if s < reach:
                dup_obj += 1
            reach = max(reach, e)
            covered += e - s
        c = committed.get(p, 0)
        unsafe += c > prefix
        rep["partitions"][p] = {"records": len(values), "committed": c, "verified_prefix": prefix,
                                "complete": prefix >= len(values), "duplicate_objects": dup_obj,
                                "duplicate_records": covered - min(prefix, len(values)) if prefix >= len(values) else None}
    rep["unsafe_commits"] = unsafe
    return rep


def trial(out: Path, topic: str, idx: int, kills: int, truth, rng: random.Random) -> dict:
    root = out / "raw" / f"{topic}-t{idx:02d}"
    shutil.rmtree(root, ignore_errors=True)
    group = f"vtop-lab-{topic}-{idx}-{int(time.time())}"
    run = KafkaRun(root, Variant(topic, max_bytes=4 * 2**20, max_age_s=1), topic, group)
    total = {p: len(v) for p, v in truth.items()}

    def drained():
        c = run.ledger_committed()
        return all(c.get(p, 0) >= n for p, n in total.items())

    events, snaps = [], []
    outage_life = rng.randrange(kills)
    for life in range(kills):
        run.start(); t0 = time.time()
        life_len = rng.uniform(1.5, 5.0)
        outage = None
        if life == outage_life:
            o0, ol = rng.uniform(0.5, life_len * 0.6), rng.uniform(1.0, 3.0)
            outage = (round(o0, 3), round(ol, 3))
            threading.Timer(o0, lambda: sh("docker", "pause", CONTAINER)).start()
            threading.Timer(o0 + ol, lambda: sh("docker", "unpause", CONTAINER)).start()
        while time.time() - t0 < life_len and not drained():
            time.sleep(0.05)
        if outage:
            time.sleep(max(0.0, outage[0] + outage[1] + 0.1 - (time.time() - t0)))
            sh("docker", "unpause", CONTAINER)
        run.kill()
        bc = run.broker_committed()
        o = oracle_kafka(run, truth, bc)
        snaps.append(o["unsafe_commits"])
        events.append({"life": life, "ran_s": round(time.time() - t0, 3), "outage": outage, "broker_committed": bc,
                       "unsafe": o["unsafe_commits"]})
        if drained():
            break
    run.start(); t0 = time.time()
    while time.time() - t0 < 900 and not drained():
        time.sleep(0.1)
    drain_s = time.time() - t0
    time.sleep(1.0)
    run.stop()
    bc = run.broker_committed()
    o = oracle_kafka(run, truth, bc)
    parts = o["partitions"].values()
    rec = {"scenario": f"kafka-{topic}", "trial": idx, "kills": len(events), "events": events,
           "unsafe_commits_at_crash": sum(snaps), "unsafe_commits_final": o["unsafe_commits"],
           "bad_objects_final": len(o["bad_objects"]), "complete": all(p["complete"] for p in parts),
           "lost_records": sum(max(0, p["records"] - p["verified_prefix"]) for p in parts),
           "duplicate_objects": sum(p["duplicate_objects"] for p in parts),
           "duplicate_records": sum(p["duplicate_records"] or 0 for p in parts),
           "records": sum(total.values()), "manifests": o["manifests"],
           "manifest_start_understated": o["manifest_start_understated"],
           "final_drain_s": round(drain_s, 3), "broker_committed_final": bc, "ledger_states": run.ledger_states()}
    rec["replay_amplification"] = round(rec["duplicate_records"] / rec["records"], 6)
    shutil.rmtree(root / "raw" / "objects", ignore_errors=True)
    shutil.rmtree(root / "raw" / "work", ignore_errors=True)
    return rec


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--trials", type=int, default=8)
    ap.add_argument("--kills", type=int, default=4)
    ap.add_argument("--seed", type=int, default=20261110)
    ap.add_argument("--topics", default="ssh-p1,hdfs-p4")
    a = ap.parse_args()
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    rng = random.Random(a.seed)
    broker_up()
    work = out / "raw"; work.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    truth = prepare_topics(work)
    meta = {"experiment": "E-RQ1-F (Kafka)", "vtop_commit": VTOP_COMMIT, "host": host_info(), "seed": a.seed,
            "kafka_image": KAFKA_IMAGE, "topics": {t: {"dataset": d, "limit": l, "partitions": p,
                                                       "records": sum(len(x) for x in truth[t].values())}
                                                   for t, (d, l, p) in TOPICS.items()},
            "prepare_s": round(time.time() - t0, 1), "started_at": time.strftime("%Y-%m-%dT%H:%M:%S%z")}
    (out / "run.json").write_text(json.dumps(meta, indent=1))
    with open(out / "trials.jsonl", "a") as fh:
        for topic in a.topics.split(","):
            n = a.trials if topic == "ssh-p1" else max(3, a.trials * 3 // 4)
            for i in range(n):
                rec = trial(out, topic, i, a.kills, truth[topic], rng)
                fh.write(json.dumps(rec) + "\n"); fh.flush()
                print(f"{topic} t{i:02d} kills={rec['kills']} unsafe={rec['unsafe_commits_at_crash']}/{rec['unsafe_commits_final']} "
                      f"complete={rec['complete']} lost={rec['lost_records']} dupobj={rec['duplicate_objects']} "
                      f"duprec={rec['duplicate_records']} drain={rec['final_drain_s']}s", flush=True)
    meta["finished_at"] = time.strftime("%Y-%m-%dT%H:%M:%S%z")
    (out / "run.json").write_text(json.dumps(meta, indent=1))
    sh("docker", "rm", "-f", CONTAINER)


if __name__ == "__main__":
    main()
